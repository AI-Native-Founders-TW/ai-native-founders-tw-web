function inPoly(lat: number, lon: number, poly: [number, number][]) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [yi, xi] = poly[i];
    const [yj, xj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

// 每個多邊形的外框：點陣產生時 isLand 會被呼叫十幾萬次，先用外框排除，才做逐邊判定
const BBOX = LAND.map((poly) => {
  let minLat = Number.POSITIVE_INFINITY;
  let maxLat = Number.NEGATIVE_INFINITY;
  let minLon = Number.POSITIVE_INFINITY;
  let maxLon = Number.NEGATIVE_INFINITY;
  for (const [la, lo] of poly) {
    if (la < minLat) minLat = la;
    if (la > maxLat) maxLat = la;
    if (lo < minLon) minLon = lo;
    if (lo > maxLon) maxLon = lo;
  }
  return [minLat, maxLat, minLon, maxLon] as const;
});

/** lon 可以是 -180–180 或 0–360 */
export function isLand(lat: number, lon: number) {
  const l = lon < 0 ? lon + 360 : lon;
  for (let i = 0; i < LAND.length; i++) {
    const b = BBOX[i];
    if (lat < b[0] || lat > b[1] || l < b[2] || l > b[3]) continue;
    if (inPoly(lat, l, LAND[i])) return true;
  }
  return false;
}
