// 章節 03 的地理資料與航線數學（不依賴 Three.js，SVG 版、HTML 疊層與 WebGL 版共用）。

export type V3 = [number, number, number];

/** 機場座標（度） */
export const TPE = { lat: 25.0797, lon: 121.2342 };
export const SFO = { lat: 37.6213, lon: -122.379 };
export const EARTH_KM = 6371;

/** 航線上四個檢查點的位置（0–1，沿航線） */
export const CHECKPOINT_T = [0.2, 0.4, 0.6, 0.8];

const D2R = Math.PI / 180;

/** 經緯度 → 單位球座標（y 朝北極；經度 0 朝 +z）。 */
export function toVec(lat: number, lon: number): V3 {
  const la = lat * D2R;
  const lo = lon * D2R;
  return [Math.cos(la) * Math.sin(lo), Math.sin(la), Math.cos(la) * Math.cos(lo)];
}

export function toLatLon(v: V3) {
  const [x, y, z] = v;
  const r = Math.hypot(x, y, z);
  return { lat: Math.asin(y / r) / D2R, lon: Math.atan2(x, z) / D2R };
}

export const dot = (a: V3, b: V3) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
export const add = (a: V3, b: V3): V3 => [a[0] + b[0], a[1] + b[1], a[2] + b[2]];
export const sub = (a: V3, b: V3): V3 => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
export const scale = (a: V3, s: number): V3 => [a[0] * s, a[1] * s, a[2] * s];
export const cross = (a: V3, b: V3): V3 => [
  a[1] * b[2] - a[2] * b[1],
  a[2] * b[0] - a[0] * b[2],
  a[0] * b[1] - a[1] * b[0],
];
export const norm = (a: V3): V3 => scale(a, 1 / (Math.hypot(a[0], a[1], a[2]) || 1));

const A = toVec(TPE.lat, TPE.lon);
const B = toVec(SFO.lat, SFO.lon);
const OMEGA = Math.acos(dot(A, B));

/** 大圓航線的總長度（公里） */
export const ROUTE_KM = OMEGA * EARTH_KM;

/** 航線在地表的點（t: 0 = 台北，1 = 舊金山） */
export function ground(t: number): V3 {
  const s = Math.sin(OMEGA);
  const a = Math.sin((1 - t) * OMEGA) / s;
  const b = Math.sin(t * OMEGA) / s;
  return [A[0] * a + B[0] * b, A[1] * a + B[1] * b, A[2] * a + B[2] * b];
}

/** 航線在空中的點（中段抬高，像一道光弧） */
export const LIFT = 0.055;
export function air(t: number): V3 {
  return scale(ground(t), 1 + LIFT * Math.sin(Math.PI * t));
}

/** 沿航線前進方向（單位向量，切於地表） */
export function tangent(t: number): V3 {
  const e = 0.002;
  return norm(sub(ground(Math.min(1, t + e)), ground(Math.max(0, t - e))));
}

/** 地表某點的「東方」單位向量 */
export function east(v: V3): V3 {
  return norm(cross([0, 1, 0], v));
}

export function formatLatLon(v: V3) {
  const { lat, lon } = toLatLon(v);
  const la = `${Math.abs(lat).toFixed(2)}°${lat >= 0 ? 'N' : 'S'}`;
  const lo = `${Math.abs(lon).toFixed(2)}°${lon >= 0 ? 'E' : 'W'}`;
  return `${la} ${lo}`;
}

